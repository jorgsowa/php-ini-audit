def default(name: str) -> Optional[str]:
    entry = KNOWN.get(name)
    return entry[0] if entry else None


def is_known(name: str) -> bool:
    return name in KNOWN


def settable_per_dir(name: str) -> bool:
    """Whether .user.ini / .htaccess may change the directive; unknown names get the benefit of the doubt."""
    entry = KNOWN.get(name)
    if entry is None:
        return True
    return bool(entry[1] & Mode.PERDIR)


def removed_in(name: str) -> Optional[str]:
    if name in OBSOLETE:
        return OBSOLETE[name]
    for prefix, version in OBSOLETE_PREFIXES.items():
        if name.startswith(prefix):
            return version
    return None


def version_tuple(text: str) -> Tuple[int, int]:
    major, _, minor = text.partition(".")
    return int(major), int(minor or 0)
